function readValueFromSeed(kind: StatKind, seed: PlayerSeed): { value: number; secondary: number | null } {
  switch (kind) {
    case 'goals':
      return { value: seed.goals, secondary: null };
    case 'assists':
      return { value: seed.assists, secondary: null };
    case 'combined':
      return { value: seed.goals + seed.assists, secondary: seed.assists };
    case 'shots':
      return { value: seed.shots, secondary: null };
    case 'shotsOn':
      return { value: seed.shotsOn, secondary: null };
    case 'keyPasses':
      return { value: seed.keyPasses, secondary: null };
    case 'dribbles':
      return { value: seed.dribbles, secondary: null };
    case 'duels':
      return { value: seed.duels, secondary: null };
    case 'penaltiesScored':
      return { value: seed.penaltiesScored, secondary: null };
    case 'foulsDrawn':
      return { value: seed.foulsDrawn, secondary: null };
    case 'tackles':
      return { value: seed.tackles, secondary: null };
    case 'interceptions':
      return { value: seed.interceptions, secondary: null };
    case 'yellow':
      return { value: seed.yellow, secondary: null };
    case 'red':
      return { value: seed.red, secondary: null };
    case 'saves':
      return { value: seed.saves, secondary: null };
    case 'conceded':
      return { value: seed.conceded, secondary: null };
    case 'rating':
      return { value: seed.rating, secondary: null };
    case 'xg':
      return { value: seed.xg, secondary: null };
    default:
      return { value: seed.goals, secondary: null };
  }
}

export function getCuratedLeagueStats(leagueId: string, kind: StatKind): StatRow[] {
  const roster = LEAGUE_ROSTERS[leagueId] || LEAGUE_ROSTERS['39']; // Fallback to Premier League star set if not configured
  if (!roster || roster.length === 0) return [];

  const rows = roster
    .map((seed) => {
      const { value, secondary } = readValueFromSeed(kind, seed);
      if (kind === 'saves' || kind === 'conceded') {
        if (seed.position !== 'Goalkeeper' && seed.saves === 0) return null;
      }
      return {
        rank: 0,
        name: seed.arabicName,
        slug: seed.slug,
        photoUrl: seed.photoUrl,
        teamName: seed.teamName,
        teamLogo: seed.teamLogo,
        teamSlug: seed.teamSlug,
        value,
        secondary,
        appearances: seed.appearances,
        minutes: seed.minutes,
        position: seed.position,
      };
    })
    .filter((row): row is NonNullable<typeof row> => row !== null && row.value > 0);

  rows.sort((a, b) => {
    if (kind === 'conceded') {
      return a.value - b.value; // For goalkeepers, fewer conceded is better
    }
    return b.value - a.value;
  });

  return rows.map((row, index) => ({
    ...row,
    rank: index + 1,
  }));
}
